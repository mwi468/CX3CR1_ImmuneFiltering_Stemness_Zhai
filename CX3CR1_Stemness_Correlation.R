rm(list=ls())

library(ggplot2)
library(matrixStats)
library(dplyr)

# Correlation between CX3CR1 expression and stemness
# in metastatic castration-resistant prostate cancer (mCRPC).
#
# Update in_dir to specify the location of the TPM expression
# matrices.
#
# Run the immune-filtering script before running this script.
# The ImmuneFiltered_Final.rds file must be present in the
# current working directory.
#
# All results and plots are saved in the current working directory.


#########################################
#### Set directories

# Input directory containing TPM expression files (TXT)
in_dir <- "D:/SharedDesktopFiles/SharedDesktopFiles"

# Output directory where results and plots are saved
out_dir <- getwd()


#########################################
#### Load needed data

# Two RNA-seq gene expression matrices comprising 210 mCRPC
# tumor biopsies from the WCDT and PROMOTE cohorts,
# as analyzed by Lundberg et al. (PMID: 37289025).

# WCDT gene expression data (TPM)
xa <- read.table(file.path(in_dir, "Lundberg_at_al/counts_and_TPMs/Counts_TPM_Genes.txt"),
                 header=TRUE, check.names=FALSE)

# PROMOTE gene expression data (TPM)
xb <- read.table(file.path(in_dir, "Lundberg_at_al/counts_and_TPMs/Counts_TPM_Genes_PROMOTE.txt"),
                 header=TRUE, check.names=FALSE)

# Merge gene expression datasets by FEATURE_ID
x1 <- merge(xa[,colnames(xa) != "gene_name"], xb, by="FEATURE_ID")

rm(xa, xb)


#########################################
#### Select stemness genes and CX3CR1

# Five stemness-associated genes and CX3CR1
genes <- c("SALL4", "POU5F1", "ALDH1A1", "NANOG", "NR5A2", "CX3CR1")

# Verify that all required genes are present
stopifnot(all(genes %in% x1$gene_name))

# Subset expression of selected genes
x2 <- x1[match(genes, x1$gene_name),]

sample_cols <- setdiff(colnames(x2), c("FEATURE_ID", "gene_name"))

t1 <- data.frame(t(x2[,sample_cols]), check.names=FALSE)
colnames(t1) <- x2$gene_name

# Verify sample count and expression values
stopifnot(nrow(t1) == 210,
          all(is.finite(as.matrix(t1))),
          all(t1 >= 0))


#########################################
#### Log2 fold-change normalization

# Fold change = (TPM + 1) / Average(TPM + 1)
#
# The reference mean expression for each gene is calculated
# across all 210 tumor samples before immune filtering.

n.exp <- t1

for (i in 1:ncol(t1)) {
  
  n.exp[,i] <- log2((t1[,i] + 1)/mean(t1[,i] + 1))
  
}


#########################################
#### Move CX3CR1 to the last column

n.exp <- n.exp %>% relocate(CX3CR1, .after=last_col())


#########################################
#### Calculate median stemness score

# Calculate the median log2 fold-change expression
# of the five stemness genes, excluding CX3CR1.

test <- as.matrix(n.exp[,1:(ncol(n.exp)-1)])

n.exp$median <- rowMedians(test)

# Save normalized expression and stemness scores
# for all 210 tumor samples (CSV)
write.csv(n.exp, file.path(out_dir, "Stemness_AllSamples.csv"))


#########################################
#### Load immune-filtered samples

# RDS file generated by the immune-filtering script
df <- readRDS(file.path(out_dir, "ImmuneFiltered_Final.rds"))

# Verify that all immune-filtered samples are present
stopifnot(all(rownames(df) %in% rownames(n.exp)))

# Retain samples that passed immune filtering
n.exp <- n.exp[rownames(n.exp) %in% rownames(df),,drop=FALSE]

# Dimensions after immune filtering
print(dim(n.exp))


#########################################
#### Pearson and Spearman correlation

# Pearson correlation between median stemness
# expression and CX3CR1 expression
ct <- cor.test(n.exp$median, n.exp$CX3CR1,
               method="pearson")

# Spearman rank correlation
st <- cor.test(n.exp$median, n.exp$CX3CR1,
               method="spearman", exact=FALSE)

print(ct)
print(st)

# Summarize correlation results
results <- data.frame(
  N=nrow(n.exp),
  Pearson_r=unname(ct$estimate),
  Pearson_p=ct$p.value,
  Spearman_rho=unname(st$estimate),
  Spearman_p=st$p.value
)

print(results, digits=8)

#########################################
#### Plot correlation

# Axis ranges based on the original manuscript figure
# Extend limits if any observations fall outside these ranges

x_limits <- range(c(-3.05, 1.25, n.exp$median))
y_limits <- range(c(-3.25, 2, n.exp$CX3CR1))

p <- ggplot(n.exp, aes(x=median, y=CX3CR1)) +
  
  geom_point(size=1.6, color="black") +
  
  geom_smooth(method="lm", formula=y~x,
              color="royalblue", fill="grey70",
              linewidth=0.8, alpha=0.6,
              level=0.95) +
  
  xlab("STEMNESS INDEX\nLog\u2082 (Fold Change)") +
  
  ylab("CX3CR1 EXPRESSION\nLog\u2082 (Fold Change)") +
  
  scale_x_continuous(
    breaks=seq(floor(x_limits[1]), ceiling(x_limits[2]), 1),
    minor_breaks=seq(floor(x_limits[1]), ceiling(x_limits[2]), 0.5)
  ) +
  
  scale_y_continuous(
    breaks=seq(floor(y_limits[1]), ceiling(y_limits[2]), 1),
    minor_breaks=seq(floor(y_limits[1]), ceiling(y_limits[2]), 0.5)
  ) +
  
  coord_cartesian(
    xlim=x_limits,
    ylim=y_limits,
    expand=FALSE
  ) +
  
  theme_bw(base_size=14) +
  
  theme(
    axis.title=element_text(face="bold", size=14),
    axis.text=element_text(face="bold", size=12, color="black"),
    
    panel.grid.major=element_line(color="grey90", linewidth=0.4),
    panel.grid.minor=element_line(color="grey95", linewidth=0.3),
    
    panel.border=element_rect(color="grey40", linewidth=0.6),
    axis.ticks=element_line(color="grey40"),
    
    axis.title.x=element_text(margin=margin(t=10)),
    axis.title.y=element_text(margin=margin(r=10)),
    
    plot.margin=margin(15, 15, 15, 15)
  )

print(p)


#########################################
#### Plot correlation with statistics

p_stats <- p +
  
  annotate("text",
           x=-Inf, y=Inf,
           hjust=-0.1, vjust=1.3,
           label=sprintf("Pearson r = %.2f\nP = %.2e\nN = %d",
                         ct$estimate,
                         ct$p.value,
                         nrow(n.exp)),
           size=4,
           fontface="bold")

print(p_stats)


#########################################
#### Save results

# Normalized expression and stemness scores
# for immune-filtered samples (CSV)
write.csv(n.exp, file.path(out_dir, "Stemness_Final.csv"))

# Normalized expression and stemness scores (RDS)
saveRDS(n.exp, file.path(out_dir, "Stemness_Final.rds"))

# Pearson and Spearman correlation results (CSV)
write.csv(results,
          file.path(out_dir, "Stemness_Correlation_Results.csv"),
          row.names=FALSE)


#########################################
#### Save correlation plots without statistics

# Correlation plot (PDF)
ggsave(file.path(out_dir, "CX3CR1_Stemness_Final.pdf"),
       plot=p, width=7, height=5)

# High-resolution correlation plot (PNG)
ggsave(file.path(out_dir, "CX3CR1_Stemness_Final.png"),
       plot=p, width=7, height=5, dpi=600)


#########################################
#### Save correlation plots with statistics

# Correlation plot with statistics (PDF)
ggsave(file.path(out_dir, "CX3CR1_Stemness_Final_Stats.pdf"),
       plot=p_stats, width=7, height=5)

# High-resolution correlation plot with statistics (PNG)
ggsave(file.path(out_dir, "CX3CR1_Stemness_Final_Stats.png"),
       plot=p_stats, width=7, height=5, dpi=600)